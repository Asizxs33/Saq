"use strict";
/**
 * Контекстные фильтры — отсекают два класса ложных срабатываний, найденных
 * при замере точности на размеченной выборке (см. eval/).
 *
 * 1. РАЗГОВОР О МОШЕННИЧЕСТВЕ, А НЕ САМО МОШЕННИЧЕСТВО.
 *    Предупреждение АФМ, новость о приговоре, памятка банка и урок финансовой
 *    грамотности содержат ровно ту же лексику, что и схема: «гарантированный
 *    доход», «осталось мало мест», «никому не говорите». На замере пять из
 *    восьми ложных срабатываний были именно такими. Помечать предупреждение
 *    о пирамиде как пирамиду — хуже, чем пропустить: пользователь перестаёт
 *    доверять уведомлениям.
 *
 * 2. СЛАБЫЙ СИГНАЛ БЕЗ ДЕНЕЖНОГО КОНТЕКСТА.
 *    «Только сегодня» в рекламе скидок и «приведи друга» в акции спортзала —
 *    те же конструкции, что у схемы, но без вложения денег под процент это
 *    обычный маркетинг. Поэтому слабые признаки (срочность, рефералы,
 *    эксклюзивность, просьба молчать) засчитываются лишь в паре и только
 *    при явном денежном контексте, а сильные (обещание процента, гарантия
 *    дохода, «вложи → получи») срабатывают сами по себе.
 */

// Рамка «об этом рассказывают», а не «это предлагают».
const WARNING_FRAME = [
  // русский
  /(^|[^а-яё])(афм|аррфр|кфгд|нацбанк|регулятор)([^а-яё]|$).{0,40}(предупрежда|сообщ|выявил|пресёк)/i,
  /(предупрежда[ею]т|памятка|осторожно|внимание).{0,60}(мошенник|пирамид|схем|обман)/i,
  /(мошенники|аферисты|злоумышленники)\s+(используют|применяют|пишут|обещают|действуют)/i,
  /(это|являются|налицо)\s+признак[а-яё]*\s+(финансов[а-яё]+[ ]+)?пирамид/i,
  /(не переводите|не отправляйте|не поддавайтесь|будьте бдительны|не ведитесь)/i,
  /(^|[^а-яё])(суд|следстви|уголовн[а-яё]* дело).{0,50}(пирамид|мошенничеств|приговор)/i,
  /(выявлен[а-яё]*|пресечен[а-яё]*|закрыт[а-яё]*)\s+(финансов[а-яё]+[ ]+)?пирамид/i,
  /(пострадал[а-яё]+|обманут[а-яё]+)\s+(более\s+)?\d/i,
  /(разбирали|изучали|урок|лекци)[а-яё]*.{0,40}(пирамид|финансов[а-яё]+ грамотн)/i,
  /выплаты\s+стар[а-яё]+[ ]+участник[а-яё]+\s+идут\s+из\s+взнос/i,
  // казахский
  /(ескерте|ескертеді|абай болыңыз|сақ болыңыз)/i,
  /(алаяқ|пирамида)[а-яёәғқңөұүhі]*.{0,40}(анықтал|әшкерелен|жабыл)/i,
  /(бұл|мұндай)\s+.{0,20}(пирамида|алаяқтық)[а-яёәғқңөұүhі]*[ ]+белгіс/i,
];

// Деньги вкладывают под доход — не просто упоминаются.
const MONEY_CONTEXT =
  /(вложи|вклад|инвест|депозит|взнос|перевед|переч|салыңыз|салса|жарна|аудар|доход|прибыл|пайда|табыс|заработ|выплат|процент|%|тенге|тг\b|₸|kaspi|каспи)/i;

/** Похоже ли, что текст ПРЕДУПРЕЖДАЕТ о схеме, а не предлагает её. */
function isWarningContext(text) {
  return WARNING_FRAME.some((re) => re.test(text));
}

/** Есть ли в тексте денежный контекст. */
function hasMoneyContext(text) {
  return MONEY_CONTEXT.test(text);
}

module.exports = { isWarningContext, hasMoneyContext };
