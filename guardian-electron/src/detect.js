"use strict";
const { isWarningContext, hasMoneyContext } = require("./context.js");
/**
 * Детектор подозрительного текста — портирован из Python-версии
 * (guardian/guardian_app.py), логика и паттерны 1-в-1, только синтаксис JS.
 */

const DOMAIN_RE = /\b([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}\b/gi;
const PHONE_RE = /(?<!\d)(\+?\d[\d\-\s()]{7,16}\d)(?!\d)/g;

// Казахский добавлен отдельно: в Казахстане рассылки часто приходят именно
// на нём, а прежний словарь был только русским — сообщение «300% пайда
// кепілдендіріледі» не ловилось вообще, хотя тот же текст по-русски давал
// пять срабатываний.
const PYRAMID_KEYWORDS = [
  "кепілдендірілген табыс",
  "кепілді табыс",
  "пайда кепілдендіріледі",
  "досыңды шақыр",
  "инвестициялық клуб",
  "гарантированный доход",
  "гарантированная прибыль",
  "x2 за неделю",
  "удвоим ваш",
  "пассивный доход от",
  "инвестируй сегодня",
  "приведи друга и получи",
  "быстрый заработок без вложений",
];

// точные фразы ловят мало — реальное сообщение мошенника («вложите 50 000,
// через неделю получите 300% прибыли, не рассказывайте никому») ни одной
// из PYRAMID_KEYWORDS не поймало. Паттерны ловят СТРУКТУРУ развода.
// Третий элемент — вес признака. "strong" достаточно сам по себе: обещание
// процента или гарантии дохода вне схемы почти не встречается. "weak"
// (срочность, рефералы, эксклюзивность, секретность) живёт и в обычной
// рекламе, поэтому засчитывается только в паре и при денежном контексте —
// иначе акция спортзала «приведи друга» попадает в выборку.
const PYRAMID_PATTERNS = [
  [/\d{2,4}\s?%.{0,25}(прибыл|доход|дней|недел|месяц)/i, "обещание конкретного % прибыли за срок", "strong"],
  [/(вложите?|инвестируй|переведите|закидыва|заноси).{0,45}(получите?|получаешь|заработа|прибыл|заберёте?|забираешь|вернём|вернем|отдадим)/i, "схема «вложи сейчас → получи потом»", "strong"],
  [/(количество мест|осталось \d+ мест|только сегодня|акция закан)/i, "искусственная срочность/ограниченность", "weak"],
  [/(не рассказывайте|никому не говор|держите в тайне)/i, "просьба скрывать предложение от других", "weak"],
  [/(вы (были )?выбраны|эксклюзивн(ая|ое) (программ|предложени|возможност)|избранн)/i, "фальшивая эксклюзивность «вас выбрали»", "weak"],
  [/приведи? друга.{0,20}(получ|бонус|%)/i, "реферальная вербовка", "weak"],
  // ниже — структуры, добавленные после разбора пропущенных сообщений:
  // «взнос 100 000 — выплата 400 000», «вход 50к, выход с х3», «удвоим за неделю»
  [/(взнос|вход|старт)[а-яё]*\s*(от\s*)?[\d\s]{3,}.{0,30}(выплат|выход|заберёш|забираеш|получ)/i, "взнос сейчас — выплата потом", "strong"],
  [/[xх]\s?[2-9].{0,30}(через|за)\s*\d+\s*(день|дней|недел|месяц)/i, "обещание кратного умножения за срок", "strong"],
  [/(удво|утро|в[ ]*[0-9]+[ ]*раза?)[а-яё]*.{0,30}(вложен|депозит|деньг|сумм)/i, "обещание умножения вложения", "strong"],
];

// отдельная категория — не «пирамида», а азартные игры/казино-контент.
// Другой тип риска (финансовый/психологический, часто нацелен на несовершеннолетних
// через стримы), поэтому размечаем отдельным kind и даём другой совет в UI.
const CASINO_KEYWORDS = [
  "gates of olympus", "sweet bonanza", "book of ra", "sugar rush",
  "фриспины", "фри спины", "бонус на депозит", "промокод на казино",
  "выбил миллион", "занос недели", "слот-машина", "джекпот казино",
];
// ── казахский: те же схемы, другой язык ────────────────────────────
const PYRAMID_PATTERNS_KZ = [
  [/\d{2,4}\s?%.{0,30}(пайда|табыс|күн|апта|ай|кіріс)/i, "обещание конкретного % прибыли за срок (каз.)", "strong"],
  [/(кепілдендірілген|кепілді|кепілдендіріледі).{0,30}(табыс|пайда|кіріс)/i, "обещание гарантированного дохода (каз.)", "strong"],
  [/(жарна|салыңыз|салып|аударыңыз).{0,45}(аласыз|табыс|пайда|қайтарамыз)/i, "схема «вложи сейчас → получи потом» (каз.)", "strong"],
  [/(орын(дар)?\s*шектеул|тек\s*\d+\s*(адам|орын)|бүгін ғана|орын қалды)/i, "искусственная срочность или ограниченность мест (каз.)", "weak"],
  [/(ешкімге айтпа|құпия сақтал|жасырын ұста)/i, "просьба скрывать предложение от других (каз.)", "weak"],
  [/(іріктелдіңіз|таңдалдыңыз|сіз таңдал|эксклюзивті ұсыныс)/i, "фальшивая эксклюзивность «вас выбрали» (каз.)", "weak"],
  [/(дос(ың|тарың)ды|таныс(ың|тарың)ды).{0,30}(шақыр|бонус|сыйақы)/i, "реферальная вербовка (каз.)", "weak"],
  [/(лицензия.{0,25}(сұрақ қоймаңыз|қажет емес|жоқ)|лицензиясыз)/i, "работа без лицензии (каз.)", "strong"],
  [/(екі есе|үш есе|еселеп?|көбейт)[а-яёәғқңөұүhі]*.{0,30}(ақша|сома|салым|қаржы)|(ақша|салым)[а-яёәғқңөұүhі]*.{0,25}(екі есе|көбейт)/i, "обещание умножения вложения (каз.)", "strong"],
];

const CASINO_PATTERNS = [
  [/(казино|слот|автомат).{0,25}(депозит|ставк|выигрыш|занос)/i, "реклама онлайн-казино/ставок"],
  [/(выбил|занёс|сорвал).{0,20}(миллион|тысяч|\d{3,}\s?[₽р$])/i, "демонстрация «выигрыша» — приманка для зрителя"],
];

const DOMAIN_IGNORE_SUFFIXES = [
  "microsoft.com", "windows.com", "google.com", "gstatic.com",
  "localhost", "vercel.app",
];

// без этого списка «домен» ловится в любом имени файла (ui.html, test.txt) —
// проверено вживую, реестр забивался хламом из OCR-мусора
const VALID_TLDS = new Set([
  "com", "net", "org", "info", "biz", "io", "co", "app", "dev", "ai", "me",
  "shop", "site", "online", "store", "club", "top", "xyz", "pro", "cc", "tv",
  "kz", "ru", "ua", "by", "uz", "kg", "tj", "az", "ge", "am", "md",
  "tr", "cn", "in", "de", "fr", "uk", "eu", "pl", "cz", "lv", "lt", "ee",
  "su", "рф", "қаз", "onion",
]);

/** Возвращает [{value, kind}], kind ∈ 'domain' | 'phone' | 'phrase'. */
function extractCandidates(text) {
  const out = [];
  const lower = text.toLowerCase();

  // Предупреждение о схеме содержит ту же лексику, что и схема. Помечать
  // памятку банка или новость о приговоре как пирамиду — хуже, чем пропустить
  // одно сообщение: человек перестаёт доверять уведомлениям. Домены и номера
  // из такого текста тоже не нужны — это реквизиты новости, а не приманки.
  if (isWarningContext(text)) return out;

  for (const m of text.matchAll(DOMAIN_RE)) {
    const d = m[0].toLowerCase();
    const tld = d.split(".").pop();
    if (!VALID_TLDS.has(tld)) continue; // имя файла или мусор OCR
    if (!DOMAIN_IGNORE_SUFFIXES.some((s) => d === s || d.endsWith("." + s))) {
      out.push({ value: d, kind: "domain" });
    }
  }

  for (const m of text.matchAll(PHONE_RE)) {
    const raw = m[0].trim();
    const digits = raw.replace(/\D/g, "");
    // настоящий номер: 10-13 цифр И ведущая 7/8 — иначе случайный забег
    // цифр вроде risk-score, попавшего в кадр
    if (digits.length >= 10 && digits.length <= 13 && (digits[0] === "7" || digits[0] === "8")) {
      out.push({ value: raw, kind: "phone" });
    }
  }

  for (const kw of PYRAMID_KEYWORDS) {
    if (lower.includes(kw)) out.push({ value: kw, kind: "phrase" });
  }

  // Признаки собираем отдельно: сильные засчитываются сами по себе, слабые —
  // только в паре и при денежном контексте. Разбор на выборке показал, что
  // одиночная «срочность» или «приведи друга» чаще всего оказывается обычной
  // рекламой скидки или акцией спортзала, а не схемой.
  const strong = [];
  const weak = [];
  for (const [rex, label, weight] of [...PYRAMID_PATTERNS, ...PYRAMID_PATTERNS_KZ]) {
    const m = text.match(rex);
    if (!m) continue;
    let snippet = m[0].trim();
    if (snippet.length > 80) snippet = snippet.slice(0, 80) + "…";
    (weight === "weak" ? weak : strong).push({ value: `${snippet} (${label})`, kind: "phrase" });
  }
  if (strong.length) {
    out.push(...strong, ...weak);
  } else if (weak.length >= 2 && hasMoneyContext(text)) {
    out.push(...weak);
  }

  for (const kw of CASINO_KEYWORDS) {
    if (lower.includes(kw)) out.push({ value: kw, kind: "casino" });
  }
  for (const [rex, label] of CASINO_PATTERNS) {
    const m = text.match(rex);
    if (m) {
      let snippet = m[0].trim();
      if (snippet.length > 80) snippet = snippet.slice(0, 80) + "…";
      out.push({ value: `${snippet} (${label})`, kind: "casino" });
    }
  }

  return out;
}

module.exports = { extractCandidates };
